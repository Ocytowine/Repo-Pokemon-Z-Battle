/** The source enables USENEWBATTLEMECHANICS, adding 20 to every listed base power. */
export const NATURAL_GIFT_BERRIES: ReadonlyMap<string, { readonly type: string; readonly power: number }> = new Map(
  Object.entries(BERRIES_BY_TYPE).flatMap(([type, items]) => items.map((item) => [item, {
    type, power: POWER_80.has(item) ? 100 : POWER_70.has(item) ? 90 : 80,
  }] as const)),
);

export function naturalGiftProfile(item: string | null): { readonly type: string; readonly power: number } | null {
  return item === null ? null : NATURAL_GIFT_BERRIES.get(item) ?? null;
}
